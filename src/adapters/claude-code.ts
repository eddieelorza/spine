export function generate(contracts: AgentContract[]): GeneratedFile[] {
  const byName = new Map(contracts.map((c) => [c.name, c]));
  const files: GeneratedFile[] = [];

  for (const contract of [...contracts].sort((a, b) => a.name.localeCompare(b.name))) {
    files.push({
      path: `${ADAPTER_ROOT}/agents/${contract.name}.md`,
      content: subagent(contract),
    });
  }

  for (const cmd of COMMANDS) {
    const contract = cmd.agent ? byName.get(cmd.agent) : undefined;
    if (cmd.agent && !contract) continue;
    files.push({
      path: `${ADAPTER_ROOT}/commands/product/${cmd.slug}.md`,
      content: command(cmd, contract),
    });
  }

  files.push({ path: `${ADAPTER_ROOT}/README.md`, content: adapterReadme(contracts) });
  return files.sort((a, b) => a.path.localeCompare(b.path));
}

// ------------------------------------------------------------------ parts

function subagent(c: AgentContract): string {
  const front = [
    '---',
    `name: ${c.name}`,
    `description: ${JSON.stringify(oneLine(c.role))}`,
    'tools: Read, Write, Edit, Grep, Glob, Bash',
    '---',
  ].join('\n');

  return [
    front,
    '',
    BANNER(`spec/agents/${c.name}.agent.md`),
    '',
    `# ${c.name}`,
    '',
    oneLine(c.role),
    '',
    contractBlock(c),
    '',
    c.instructions,
    '',
  ].join('\n');
}

function command(cmd: CommandDef, contract?: AgentContract): string {
  const front = [
    '---',
    `description: ${JSON.stringify(cmd.description)}`,
    ...(cmd.argumentHint ? [`argument-hint: ${JSON.stringify(cmd.argumentHint)}`] : []),
    'allowed-tools: Read, Write, Edit, Grep, Glob, Bash',
    '---',
  ].join('\n');

  if (!contract) {
    return [
      front, '',
      BANNER('src/adapters/claude-code.ts'), '',
      `Run this and show the human the output verbatim. Do not summarise it or soften it —`,
      `the warnings are the point.`, '',
      '```bash',
      cmd.wraps ?? '',
      '```', '',
    ].join('\n');
  }

  return [
    front, '',
    BANNER(`spec/agents/${contract.name}.agent.md`), '',
    `Use the **${contract.name}** subagent.`, '',
    ...(cmd.preamble ? [cmd.preamble, ''] : []),
    contractBlock(contract), '',
    '---', '',
    contract.instructions, '',
  ].join('\n');
}

/** The machine-enforced half of the contract, restated where the model will read it. */
function contractBlock(c: AgentContract): string {
  const lines: string[] = ['## Your contract', ''];
  lines.push(`- **You may create:** ${c.writes.length ? c.writes.join(', ') : '_nothing — you review only_'}`);
  lines.push(`- **You may read:** ${c.reads.join(', ')}`);
  if (c.narrative_writes.length) lines.push(`- **You may write:** ${c.narrative_writes.join(', ')}`);
  if (c.preconditions.length) lines.push(`- **Before you start:** ${c.preconditions.join('; ')}`);

  const defaults = Object.entries(c.epistemic_defaults);
  if (defaults.length) {
    lines.push(`- **Epistemic defaults:** ${defaults.map(([k, v]) => `${k} → ${v?.epistemic}`).join(', ')}`);
  }

  const hard = c.prohibitions.filter((p) => p.enforced_by === 'cli');
  const soft = c.prohibitions.filter((p) => p.enforced_by === 'prompt');

  if (hard.length) {
    lines.push('', '### Enforced by the CLI — attempting these fails with exit code 4', '');
    for (const p of hard) lines.push(`- ${p.rule}`);
  }
  if (soft.length) {
    lines.push('', '### Not enforceable — these are on you', '');
    for (const p of soft) lines.push(`- ${p.rule}${p.note ? `  _(${oneLine(p.note)})_` : ''}`);
  }

  lines.push(
    '', '### Protocol', '',
    `- Pass \`--agent ${c.name}\` on every mutating command. It is how the guard-rails apply to you.`,
    '- Allocate IDs only via `product node new`. Never write an ID or YAML frontmatter yourself.',
    '- Create edges only via `product node link`.',
    '- Read context via `product context <ID>` or `product list --json`, not by reading the whole tree.',
    '- After writing, run `product check --json` and report findings. Do not silently fix them.',
    '- Never mark anything accepted. Only the human accepts.',
  );

  if (c.done_when.length) {
    lines.push('', '### Done when', '');
    for (const d of c.done_when) lines.push(`- ${d}`);
  }
  if (c.handoff.next) {
    lines.push('', `### Hand off to \`${c.handoff.next}\``, '', c.handoff.message ?? '');
  }
  return lines.join('\n');
}

function adapterReadme(contracts: AgentContract[]): string {
  return [
    BANNER('spec/agents/*.agent.md'),
    '',
    '# Claude Code adapter',
    '',
    'Generated from the tool-neutral contracts in `spec/agents/`. Regenerate with:',
    '',
    '```bash',
    'product agents build',
    '```',
    '',
    'To use these in a project, copy them into that project:',
    '',
    '```bash',
    'cp -r adapters/claude-code/agents   .claude/agents',
    'cp -r adapters/claude-code/commands .claude/commands',
    '```',
    '',
    '## Agents',
    '',
    '| Agent | Creates | CLI-enforced | On the model |',
    '|---|---|---|---|',
    ...contracts.map((c) => {
      const hard = c.prohibitions.filter((p) => p.enforced_by === 'cli').length;
      const soft = c.prohibitions.filter((p) => p.enforced_by === 'prompt').length;
      return `| \`${c.name}\` | ${c.writes.join(', ') || '_nothing_'} | ${hard} | ${soft} |`;
    }),
    '',
    '## Commands',
    '',
    ...COMMANDS.map((c) => `- \`/product:${c.slug}\` — ${c.description}`),
    '',
    'The last four are thin wrappers over the deterministic CLI. They call no model to',
    'produce their answer, which is why they can be trusted when the rest cannot.',
    '',
  ].join('\n');
}

function oneLine(s: string): string {
  return s.replace(/\s*\n\s*/g, ' ').trim();
}
